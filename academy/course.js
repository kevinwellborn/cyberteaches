// New puzzles always go at the END of LEVELS, even when they belong to an earlier lesson: n is the puzzle's saved id
// (progress, programs and the answer key are stored by n), so it must never change. ORDER is the play order, by lesson.
// Difficulty levels: every lesson has its own set of 10 puzzles per level. The teacher picks a level for the class
// (classes/{code}.level, with per-student overrides in classes/{code}.levels). Puzzles without a level are the Hard set.
const LEVEL_NAMES = {easy:'Easy', medium:'Medium', hard:'Hard'};
const LEVEL_ORDER = ['easy','medium','hard'];
const DEFAULT_LEVEL = 'hard';
LEVELS.forEach((l,i)=>{ l.level=l.level||'hard'; l.n=i+1; l.k=LEVELS.slice(0,i).filter(o=>o.unit===l.unit && o.level===l.level).length+1 });  // k: puzzle number inside its lesson and level
const ORDER = [...LEVELS].sort((a,b)=>a.unit-b.unit || LEVEL_ORDER.indexOf(a.level)-LEVEL_ORDER.indexOf(b.level) || a.k-b.k);
const LEVELS_AVAILABLE = LEVEL_ORDER.filter(v=>LEVELS.some(l=>l.level===v));   // levels that have puzzles
const levelsOf = (level, unit) => ORDER.filter(l=>l.level===level && (unit==null || l.unit===unit));   // puzzles of one level, in play order

// Ranks: students are promoted as they earn stars (3 per puzzle). Shared by the student site and the teacher dashboard.
const RANKS = [[0,'Recruit'],[10,'Private'],[30,'Corporal'],[60,'Sergeant'],[100,'Staff Sergeant'],[150,'Lieutenant'],
  [200,'Captain'],[260,'Major'],[320,'Colonel'],[380,'General']];
const totalStars = progress => LEVELS.reduce((s,l)=>s+((progress||{})[l.n]||0),0);
function rankFor(stars){
  let i=0; while(i+1<RANKS.length && stars>=RANKS[i+1][0]) i++;
  return {i, title:RANKS[i][1], min:RANKS[i][0], next:RANKS[i+1]||null};
}
// Lesson score out of 100 for the teacher dashboard: each puzzle counts 3 stars = 100, 2 stars = 90, 1 star = 80, unsolved = 0.
const STAR_SCORE = [0,80,90,100];
function lessonScore(progress, unit, level=DEFAULT_LEVEL){
  const lv=levelsOf(level, unit);
  return Math.round(lv.reduce((s,l)=>s+STAR_SCORE[(progress||{})[l.n]||0],0)/lv.length);
}
